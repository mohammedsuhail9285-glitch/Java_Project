-- Flyway Migration V1: Complete Relational Schema for RegTech Sentinel
-- Compatible with PostgreSQL 16 and H2 (PostgreSQL mode)

-- 1. Users table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(128) NOT NULL UNIQUE,
    full_name VARCHAR(128),
    role VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Sellers table
CREATE TABLE IF NOT EXISTS sellers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    location VARCHAR(255),
    state_region VARCHAR(64),
    risk_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    contact_email VARCHAR(128),
    registration_number VARCHAR(64),
    total_products INT NOT NULL DEFAULT 0,
    violation_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Brands table
CREATE TABLE IF NOT EXISTS brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    manufacturer_name VARCHAR(255),
    country_of_origin VARCHAR(64) DEFAULT 'India',
    total_products INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Categories table
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE,
    parent_category VARCHAR(128),
    risk_weight DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    mandatory_fields TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Products table
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    brand_id BIGINT,
    seller_id BIGINT,
    category_id BIGINT,
    declared_mrp DOUBLE PRECISION,
    listing_price DOUBLE PRECISION,
    description TEXT,
    country_of_origin VARCHAR(64),
    product_url VARCHAR(512),
    ingestion_source VARCHAR(64) DEFAULT 'MANUAL',
    status VARCHAR(32) DEFAULT 'PENDING_SCAN',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_products_seller_id ON products(seller_id);
CREATE INDEX IF NOT EXISTS idx_products_brand_id ON products(brand_id);
CREATE INDEX IF NOT EXISTS idx_products_category_id ON products(category_id);

-- 6. Product Listings table
CREATE TABLE IF NOT EXISTS product_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    raw_extracted_fields TEXT,
    source_type VARCHAR(64) DEFAULT 'WEB_LISTING',
    scraped_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Product Images table
CREATE TABLE IF NOT EXISTS product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    original_path VARCHAR(512) NOT NULL,
    processed_path VARCHAR(512),
    image_type VARCHAR(64) DEFAULT 'PACKAGE_LABEL',
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. OCR Results table
CREATE TABLE IF NOT EXISTS ocr_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_image_id BIGINT NOT NULL,
    raw_text TEXT,
    language VARCHAR(32) DEFAULT 'eng',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    engine VARCHAR(64) DEFAULT 'tesseract',
    processed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. Extracted Fields table
CREATE TABLE IF NOT EXISTS extracted_fields (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    field_type VARCHAR(32) NOT NULL,
    raw_value TEXT,
    normalized_value TEXT,
    unit VARCHAR(32),
    source VARCHAR(32) NOT NULL DEFAULT 'IMAGE',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    bounding_box VARCHAR(128),
    verified_by BIGINT,
    verified_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. Rules table
CREATE TABLE IF NOT EXISTS rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id VARCHAR(32) NOT NULL UNIQUE,
    rule_name VARCHAR(128) NOT NULL,
    description TEXT,
    category VARCHAR(64),
    applicable_product_category VARCHAR(128) DEFAULT 'ALL',
    severity VARCHAR(32) NOT NULL,
    validation_type VARCHAR(64) NOT NULL,
    expected_field VARCHAR(64),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version INT NOT NULL DEFAULT 1,
    effective_date DATE,
    source TEXT,
    remediation_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

-- 11. Rule Versions table
CREATE TABLE IF NOT EXISTS rule_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id VARCHAR(32) NOT NULL,
    version_number INT NOT NULL,
    config_snapshot TEXT NOT NULL,
    changed_by VARCHAR(64),
    change_reason TEXT,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 12. Compliance Checks table
CREATE TABLE IF NOT EXISTS compliance_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    scan_job_id BIGINT,
    overall_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    mandatory_field_completion_pct DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    critical_count INT NOT NULL DEFAULT 0,
    major_count INT NOT NULL DEFAULT 0,
    minor_count INT NOT NULL DEFAULT 0,
    ocr_confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    ai_confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    rule_engine_confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    risk_level VARCHAR(32) NOT NULL DEFAULT 'LOW',
    summary_notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 13. Violations table
CREATE TABLE IF NOT EXISTS violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id VARCHAR(64) NOT NULL UNIQUE,
    product_id BIGINT NOT NULL,
    rule_id VARCHAR(32) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    detected_value TEXT,
    expected_condition TEXT,
    evidence_id BIGINT,
    source VARCHAR(32) DEFAULT 'IMAGE',
    ocr_confidence DOUBLE PRECISION DEFAULT 0.0,
    detection_confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'NEW',
    reviewer_id BIGINT,
    reviewer_comment TEXT,
    resolution TEXT,
    resolution_timestamp TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_violations_status ON violations(status);
CREATE INDEX IF NOT EXISTS idx_violations_severity ON violations(severity);
CREATE INDEX IF NOT EXISTS idx_violations_rule_id ON violations(rule_id);
CREATE INDEX IF NOT EXISTS idx_violations_product_id ON violations(product_id);

-- 14. Evidences table
CREATE TABLE IF NOT EXISTS evidences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id BIGINT,
    original_image_path VARCHAR(512),
    cropped_image_path VARCHAR(512),
    ocr_text TEXT,
    source_url_or_dataset VARCHAR(512),
    bounding_box VARCHAR(128),
    detection_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 15. Reviews table
CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id BIGINT NOT NULL,
    reviewer_id BIGINT NOT NULL,
    action VARCHAR(64) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 16. Audit Logs table
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    username VARCHAR(64),
    action VARCHAR(64) NOT NULL,
    entity VARCHAR(64) NOT NULL,
    entity_id VARCHAR(64),
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip_address VARCHAR(64),
    old_value TEXT,
    new_value TEXT
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_timestamp ON audit_logs(timestamp);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id ON audit_logs(user_id);

-- 17. Notifications table
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    message TEXT NOT NULL,
    type VARCHAR(64) NOT NULL DEFAULT 'INFO',
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 18. Scan Jobs table
CREATE TABLE IF NOT EXISTS scan_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
    product_id BIGINT,
    batch_id VARCHAR(64),
    progress_pct INT NOT NULL DEFAULT 0,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 19. Scan Results table
CREATE TABLE IF NOT EXISTS scan_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_job_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    summary TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 20. Reports table
CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_name VARCHAR(255),
    requested_by BIGINT,
    format VARCHAR(32) NOT NULL,
    filters TEXT,
    file_path VARCHAR(512),
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
