-- Flyway Migration V7: Production Authentication Enhancements
-- Adds account security fields, email verification, lockout tracking, and security tokens.
-- Compatible with PostgreSQL 16 and H2 (PostgreSQL mode).

-- 1. Add security and account lifecycle columns to users table
ALTER TABLE users ADD COLUMN IF NOT EXISTS provider_id VARCHAR(128);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS account_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_login_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS locked_until TIMESTAMP;
ALTER TABLE users ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP;

-- 2. Mark pre-seeded system demo users as email-verified and active
UPDATE users 
SET email_verified = TRUE, 
    account_status = 'ACTIVE', 
    failed_login_attempts = 0,
    updated_at = CURRENT_TIMESTAMP
WHERE username IN ('admin', 'regulator', 'reviewer', 'analyst');

-- 3. Create security_tokens table for email verification and password reset
CREATE TABLE IF NOT EXISTS security_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(128) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    token_type VARCHAR(32) NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_security_tokens_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_security_tokens_token ON security_tokens(token);
CREATE INDEX IF NOT EXISTS idx_security_tokens_user_id ON security_tokens(user_id);
CREATE INDEX IF NOT EXISTS idx_security_tokens_type ON security_tokens(token_type);
