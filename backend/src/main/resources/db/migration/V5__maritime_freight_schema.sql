-- 1. Maritime Ports (East Coast of India & Global Discharge/Load Ports)
CREATE TABLE IF NOT EXISTS maritime_ports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_code VARCHAR(16) NOT NULL UNIQUE,
    port_name VARCHAR(128) NOT NULL,
    country VARCHAR(64) NOT NULL DEFAULT 'India',
    coast VARCHAR(32) NOT NULL DEFAULT 'East Coast',
    max_draft_meters DOUBLE PRECISION NOT NULL,
    max_dwt DOUBLE PRECISION NOT NULL,
    max_loa_meters DOUBLE PRECISION NOT NULL DEFAULT 280.0,
    max_beam_meters DOUBLE PRECISION NOT NULL DEFAULT 45.0,
    discharge_rate_tpd DOUBLE PRECISION NOT NULL,
    average_berth_wait_days DOUBLE PRECISION NOT NULL DEFAULT 2.5,
    congestion_index DOUBLE PRECISION NOT NULL DEFAULT 0.35,
    port_tariff_per_ton DOUBLE PRECISION NOT NULL,
    tide_restriction_notes VARCHAR(255) NOT NULL DEFAULT 'Standard semi-diurnal tides',
    lighterage_supported BOOLEAN NOT NULL DEFAULT FALSE,
    lighterage_zone VARCHAR(128),
    lighterage_tariff_per_ton DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Vessel Classes (Capesize, Panamax, Supramax, Handysize)
CREATE TABLE IF NOT EXISTS vessel_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_code VARCHAR(32) NOT NULL UNIQUE,
    class_name VARCHAR(64) NOT NULL,
    min_dwt DOUBLE PRECISION NOT NULL,
    max_dwt DOUBLE PRECISION NOT NULL,
    max_draft_meters DOUBLE PRECISION NOT NULL,
    typical_loa_meters DOUBLE PRECISION NOT NULL DEFAULT 225.0,
    typical_beam_meters DOUBLE PRECISION NOT NULL DEFAULT 32.2,
    ballast_draft_meters DOUBLE PRECISION NOT NULL DEFAULT 8.5,
    fuel_consumption_tpd DOUBLE PRECISION NOT NULL,
    daily_operating_cost_usd DOUBLE PRECISION NOT NULL,
    speed_knots DOUBLE PRECISION NOT NULL DEFAULT 13.5,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Trade Routes (Global Overseas Origins to East Coast India)
CREATE TABLE IF NOT EXISTS trade_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code VARCHAR(64) NOT NULL UNIQUE,
    origin_port VARCHAR(64) NOT NULL,
    origin_country VARCHAR(64) NOT NULL,
    destination_port_id BIGINT REFERENCES maritime_ports(id),
    commodity VARCHAR(64) NOT NULL,
    distance_nautical_miles DOUBLE PRECISION NOT NULL,
    benchmark_rate_usd_per_ton DOUBLE PRECISION NOT NULL,
    origin_max_draft_meters DOUBLE PRECISION NOT NULL DEFAULT 18.5,
    origin_max_loa_meters DOUBLE PRECISION NOT NULL DEFAULT 310.0,
    loading_rate_tpd DOUBLE PRECISION NOT NULL DEFAULT 35000.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Freight Market Indices (Baltic Dry Index, BCI, BPI, BSI & Bunker Fuel)
CREATE TABLE IF NOT EXISTS freight_market_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_date DATE NOT NULL,
    bdi INT NOT NULL,
    bci INT NOT NULL,
    bpi INT NOT NULL,
    bsi INT NOT NULL,
    bunker_vlsfo_usd DOUBLE PRECISION NOT NULL,
    usd_inr_rate DOUBLE PRECISION NOT NULL DEFAULT 83.5,
    sentiment_score DOUBLE PRECISION NOT NULL DEFAULT 0.52,
    data_source VARCHAR(64) NOT NULL DEFAULT 'HISTORICAL_BALTIC_INDEX',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Freight Rate Forecasts
CREATE TABLE IF NOT EXISTS freight_forecasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_route_id BIGINT REFERENCES trade_routes(id),
    vessel_class_code VARCHAR(32) NOT NULL,
    current_spot_rate DOUBLE PRECISION NOT NULL,
    forecast_7d DOUBLE PRECISION NOT NULL,
    forecast_14d DOUBLE PRECISION NOT NULL,
    forecast_30d DOUBLE PRECISION NOT NULL,
    lower_bound_14d DOUBLE PRECISION NOT NULL,
    upper_bound_14d DOUBLE PRECISION NOT NULL,
    trend_direction VARCHAR(16) NOT NULL,
    volatility_index VARCHAR(16) NOT NULL,
    confidence_score DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Bulk Cargo Procurement & Chartering Plans
CREATE TABLE IF NOT EXISTS procurement_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_reference VARCHAR(64) NOT NULL UNIQUE,
    commodity VARCHAR(64) NOT NULL,
    quantity_tons DOUBLE PRECISION NOT NULL,
    origin_country VARCHAR(64) NOT NULL,
    destination_port_id BIGINT REFERENCES maritime_ports(id),
    target_laycan_start DATE NOT NULL,
    target_laycan_end DATE NOT NULL,
    recommended_vessel_class VARCHAR(32) NOT NULL,
    charter_decision VARCHAR(32) NOT NULL,
    contract_type VARCHAR(32) NOT NULL DEFAULT 'SPOT',
    coa_discount_pct DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    coa_total_volume_tons DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    fob_cargo_price_usd_ton DOUBLE PRECISION NOT NULL,
    predicted_freight_usd_ton DOUBLE PRECISION NOT NULL,
    bunker_adjustment_usd_ton DOUBLE PRECISION NOT NULL,
    port_charges_usd_ton DOUBLE PRECISION NOT NULL,
    demurrage_risk_usd_ton DOUBLE PRECISION NOT NULL,
    lighterage_required BOOLEAN NOT NULL DEFAULT FALSE,
    lighterage_anchorage VARCHAR(128),
    lightered_quantity_tons DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    lighterage_cost_usd_ton DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    total_landed_cost_usd_ton DOUBLE PRECISION NOT NULL,
    total_landed_cost_inr_ton DOUBLE PRECISION NOT NULL,
    estimated_cost_savings_inr DOUBLE PRECISION NOT NULL,
    decision_rationale TEXT NOT NULL,
    demurrage_risk_level VARCHAR(32) NOT NULL DEFAULT 'LOW',
    alternative_port_recommendation VARCHAR(255),
    volatility_alert_level VARCHAR(32) NOT NULL DEFAULT 'NORMAL',
    status VARCHAR(32) NOT NULL DEFAULT 'OPTIMIZED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

