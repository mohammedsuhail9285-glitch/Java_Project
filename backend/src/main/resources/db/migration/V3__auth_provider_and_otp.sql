-- Flyway Migration V3: Support for Google OAuth and OTP Sign-In
-- Compatible with PostgreSQL 16 and H2 (PostgreSQL mode)

-- 1. Add auth_provider to users table (LOCAL, GOOGLE)
ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_provider VARCHAR(32) NOT NULL DEFAULT 'LOCAL';

-- 2. Add phone_number to users table for mobile OTP lookup
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_number VARCHAR(32);

-- 3. Allow password_hash to be nullable for OAuth-created users
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- 4. OTP Codes table for one-time password storage and verification
CREATE TABLE IF NOT EXISTS otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier VARCHAR(128) NOT NULL,
    hashed_code VARCHAR(255) NOT NULL,
    purpose VARCHAR(32) NOT NULL DEFAULT 'LOGIN',
    expires_at TIMESTAMP NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_otp_codes_identifier ON otp_codes(identifier);
CREATE INDEX IF NOT EXISTS idx_otp_codes_created_at ON otp_codes(created_at);
